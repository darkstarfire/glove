#!/bin/sh
# Puts Glove in the login screen's session list, using this project's files
# (no binaries are copied: building again is enough to update).
#   sudo ./data/install-session.sh           installs
#   sudo ./data/install-session.sh --remove  takes it off the list
set -e
dir="$(cd "$(dirname "$0")" && pwd)"
# Message language: Portuguese if the system locale is Portuguese, English otherwise.
case "${LC_ALL:-${LC_MESSAGES:-${LANG:-}}}" in pt*) lang=pt ;; *) lang=en ;; esac
t() { if [ "$lang" = pt ]; then printf '%s' "$1"; else printf '%s' "$2"; fi; }
say() { printf '%s\n' "$(t "$1" "$2")"; }

dest=/usr/share/wayland-sessions/glove.desktop
pam=/etc/pam.d/glove
launcher=/usr/local/bin/glove-session
if [ "$(id -u)" != 0 ]; then
    say "Rode com sudo." "Run with sudo." >&2
    exit 1
fi
case "${1:-}" in
    --remove|--remover)
        rm -f "$dest" "$pam" "$launcher"
        say "Glove removido da tela de login." "Glove removed from the login screen."
        exit 0
        ;;
esac
if [ ! -x "$dir/../target/release/glove" ]; then
    say "Compile antes: cargo build --release" "Build first: cargo build --release" >&2
    exit 1
fi
# The login screen runs as another user (e.g. _greetd), who cannot enter the home folder:
# an Exec pointing there vanishes from the list (or fails). The launcher lives where
# everyone can see it and only calls the project's script, which already runs as the session's user.
printf '#!/bin/sh\n# Generated by data/install-session.sh: starts the Glove session of the project.\nexec "%s/glove-session" "$@"\n' "$dir" > "$launcher"
chmod 755 "$launcher"
sed "s|^Exec=.*|Exec=$launcher|" "$dir/glove.desktop" > "$dest"
chmod 644 "$dest"
# PAM service to unlock the screen (it only checks the password). Without it, Glove uses "login".
if [ -f /etc/pam.d/common-auth ]; then
    # Debian, Ubuntu and derivatives
    printf '# Glove screen unlock\nauth    optional  pam_faildelay.so delay=2000000\n@include common-auth\n@include common-account\n' > "$pam"
elif [ -f /etc/pam.d/system-auth ]; then
    # Fedora, Arch and others
    printf '# Glove screen unlock\nauth     include  system-auth\naccount  include  system-auth\n' > "$pam"
fi
[ -f "$pam" ] && chmod 644 "$pam"
say "Pronto: saia da sessão e escolha \"Glove\" na tela de login (ícone de engrenagem)." \
    "Done: log out and choose \"Glove\" on the login screen (gear icon)."
